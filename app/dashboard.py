
"""Streamlit dashboard for Sharpness-Aware Prompt Optimization.

Reads only files generated by the pipeline. No fabricated metrics.
"""

import json
import sys
from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd
import seaborn as sns
import streamlit as st

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import config as C  # noqa: E402

PROCESSED = Path(C.DATA_DIR) / "processed"
RESULTS = Path(C.RESULTS_DIR)

MISSING = "Results not found, run `python scripts/run_all.py`."

st.set_page_config(
    page_title="Sharpness-Aware Prompt Optimization",
    layout="wide"
)

st.title("Sharpness-Aware Prompt Optimization")
st.caption("Every number here is read from files written by the pipeline.")


# ---------------- Utility functions ----------------

def load_json(path: Path):
    """Load JSON without inventing or substituting values."""
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except FileNotFoundError:
        return None
    except json.JSONDecodeError as e:
        st.error(f"Invalid JSON in {path.name}: {e}")
        return None


def load_csv(path: Path):
    try:
        return pd.read_csv(path)
    except FileNotFoundError:
        return None


def mock_banner(data, name):
    if isinstance(data, dict) and data.get("_mock"):
        st.warning(
            f"{name} is MOCK data (development only). "
            "Run the real pipeline before final submission."
        )


def missing(name):
    st.error(f"`{name}`: {MISSING}")


def confusion_heatmap(cm, title):
    labels = list(C.LABELS)

    fig, ax = plt.subplots(figsize=(5.5, 4.5))

    sns.heatmap(
        cm,
        annot=True,
        fmt="d",
        cmap="Blues",
        cbar=False,
        xticklabels=labels,
        yticklabels=labels,
        ax=ax
    )

    ax.set_xlabel("Predicted label")
    ax.set_ylabel("True label")
    ax.set_title(title)

    fig.tight_layout()
    st.pyplot(fig)
    plt.close(fig)


# ---------------- Dashboard tabs ----------------

tab_data, tab_pred, tab_sharp, tab_metrics, tab_cmp = st.tabs(
    ["Dataset", "Predictions", "Sharpness", "Metrics", "Comparison"]
)


# ---------------- Dataset ----------------

with tab_data:

    name = "data/processed/class_distribution.json"

    dist = load_json(PROCESSED / "class_distribution.json")

    if dist is None:
        missing(name)

    else:
        mock_banner(dist, name)

        splits = [
            s for s in ("train", "val", "test")
            if s in dist
        ]

        if not splits:
            st.error("Invalid class_distribution.json: no train, val or test splits found.")

        else:
            try:
                counts = pd.DataFrame({
                    s: {
                        lab: dist[s]["counts"].get(lab, 0)
                        for lab in C.LABELS
                    }
                    for s in splits
                })

                counts.index.name = "class"

                st.subheader("Class counts per split")
                st.bar_chart(counts)

                cols = st.columns(len(splits))

                for col, s in zip(cols, splits):
                    d = dist[s]

                    col.metric(
                        f"{s} (n={d['n']})",
                        f"{d['imbalance_ratio']:.1f}x imbalance"
                    )

                    col.caption(
                        f"Majority: {d['majority_class']} | "
                        f"Minority: {d['minority_class']}"
                    )

                st.subheader("Class share (%)")

                pct = pd.DataFrame({
                    s: {
                        lab: dist[s]["percent"].get(lab)
                        for lab in C.LABELS
                    }
                    for s in splits
                })

                st.dataframe(
                    pct.round(2),
                    width="stretch"
                )

            except (KeyError, TypeError, ValueError) as e:
                st.error(
                    f"Invalid class_distribution.json structure: {e}"
                )


# ---------------- Predictions ----------------

with tab_pred:

    df = load_csv(RESULTS / "paraphrase_predictions.csv")

    if df is None:
        missing("results/paraphrase_predictions.csv")

    else:
        names = list(C.LABELS)
        show = df.copy()

        for c in ("true_label", "pred_original", "pred_paraphrase"):

            if c in show.columns:

                def label_name(value):
                    try:
                        i = int(value)
                        return names[i] if 0 <= i < len(names) else value
                    except (ValueError, TypeError):
                        return value

                show[c] = show[c].map(label_name)

        only_flips = st.checkbox(
            "Show only flipped predictions"
        )

        if only_flips:
            required = {"pred_original", "pred_paraphrase"}

            if required.issubset(show.columns):
                show = show[
                    show["pred_original"] != show["pred_paraphrase"]
                ]
            else:
                st.error(
                    "Prediction CSV is missing pred_original "
                    "or pred_paraphrase columns."
                )

        st.write(f"{len(show)} rows")

        st.dataframe(
            show,
            width="stretch"
        )


# ---------------- Sharpness ----------------

with tab_sharp:

    sh = load_json(RESULTS / "sharpness.json")

    if sh is None:
        missing("results/sharpness.json")

    else:
        mock_banner(sh, "sharpness.json")

        required_sections = [
            "template_sensitivity",
            "paraphrase_sensitivity",
            "sharpness_summary"
        ]

        missing_sections = [
            key for key in required_sections
            if key not in sh
        ]

        if missing_sections:

            st.error(
                "Invalid sharpness.json structure. Missing sections: "
                + ", ".join(missing_sections)
            )

        else:

            summary = sh["sharpness_summary"]
            template_section = sh["template_sensitivity"]
            paraphrase = sh["paraphrase_sensitivity"]

            required_summary = [
                "overall_sharpness_score",
                "paraphrase_flip_rate",
                "template_mean_drop",
                "template_max_drop",
                "macro_f1_std"
            ]

            missing_summary = [
                key for key in required_summary
                if key not in summary
            ]

            if missing_summary:

                st.error(
                    "sharpness_summary is missing: "
                    + ", ".join(missing_summary)
                )

            else:

                st.subheader("Sharpness Summary")

                c1, c2, c3 = st.columns(3)

                c1.metric(
                    "Overall Sharpness Score",
                    f"{summary['overall_sharpness_score']:.4f}"
                )

                c2.metric(
                    "Paraphrase Flip Rate",
                    f"{summary['paraphrase_flip_rate']:.2%}"
                )

                c3.metric(
                    "Template Mean Drop",
                    f"{summary['template_mean_drop']:.4f}"
                )

                c4, c5 = st.columns(2)

                c4.metric(
                    "Template Maximum Drop",
                    f"{summary['template_max_drop']:.4f}"
                )

                c5.metric(
                    "Macro F1 Standard Deviation",
                    f"{summary['macro_f1_std']:.4f}"
                )

                # Template sensitivity

                st.divider()
                st.subheader("Template Sensitivity Analysis")

                template_data = template_section.get("templates", {})

                if template_data:

                    template_rows = []

                    for name, values in template_data.items():

                        template_rows.append({
                            "Template": name,
                            "Macro F1": values.get("macro_f1"),
                            "Accuracy": values.get("accuracy"),
                            "Relative Drop": values.get("relative_drop")
                        })

                    template_df = pd.DataFrame(template_rows)

                    st.dataframe(
                        template_df,
                        width="stretch"
                    )

                    st.write("Macro F1 across templates")

                    st.bar_chart(
                        template_df.set_index("Template")[["Macro F1"]]
                    )

                    st.write("Relative performance drop")

                    st.bar_chart(
                        template_df.set_index("Template")[["Relative Drop"]]
                    )

                else:
                    st.warning(
                        "No template results found in sharpness.json."
                    )

                # Paraphrase sensitivity

                st.divider()
                st.subheader("Paraphrase Sensitivity Analysis")

                required_paraphrase = [
                    "n_samples",
                    "n_flipped",
                    "flip_rate",
                    "macro_f1_gap",
                    "per_class_flip_rate"
                ]

                missing_paraphrase = [
                    key for key in required_paraphrase
                    if key not in paraphrase
                ]

                if missing_paraphrase:

                    st.error(
                        "paraphrase_sensitivity is missing: "
                        + ", ".join(missing_paraphrase)
                    )

                else:

                    p1, p2, p3 = st.columns(3)

                    p1.metric(
                        "Samples Evaluated",
                        paraphrase["n_samples"]
                    )

                    p2.metric(
                        "Flipped Predictions",
                        paraphrase["n_flipped"]
                    )

                    p3.metric(
                        "Macro F1 Gap",
                        f"{paraphrase['macro_f1_gap']:.4f}"
                    )

                    st.write("Per-class prediction flip rate")

                    flip_df = pd.DataFrame.from_dict(
                        paraphrase["per_class_flip_rate"],
                        orient="index",
                        columns=["Flip Rate"]
                    )

                    st.bar_chart(flip_df)


# ---------------- Metrics ----------------

with tab_metrics:

    files = {
        "Baseline": "baseline_metrics.json",
        "Prompt": "prompt_metrics.json",
        "Focal": "focal_metrics.json"
    }

    for title, fn in files.items():

        st.subheader(title)

        m = load_json(RESULTS / fn)

        if m is None:
            missing(f"results/{fn}")
            continue

        mock_banner(m, fn)

        required = [
            "accuracy",
            "macro_f1",
            "per_class_f1",
            "confusion_matrix"
        ]

        missing_keys = [
            key for key in required
            if key not in m
        ]

        if missing_keys:

            st.error(
                f"{fn} is missing required fields: "
                + ", ".join(missing_keys)
            )

            continue

        st.caption(
            f"Method: {m.get('method', 'Not specified')} | "
            f"n_test: {m.get('n_test', 'Not specified')}"
        )

        a, b = st.columns(2)

        a.metric(
            "Accuracy",
            f"{m['accuracy']:.4f}"
        )

        b.metric(
            "Macro F1",
            f"{m['macro_f1']:.4f}"
        )

        left, right = st.columns(2)

        with left:

            st.write("Per-class F1")

            st.bar_chart(
                pd.Series(
                    m["per_class_f1"],
                    name="F1"
                )
            )

        with right:

            st.write("Confusion Matrix")

            try:
                confusion_heatmap(
                    m["confusion_matrix"],
                    f"{title}: Confusion Matrix"
                )

            except (ValueError, TypeError) as e:
                st.error(f"Invalid confusion matrix: {e}")


# ---------------- Comparison ----------------

with tab_cmp:

    cmp_ = load_json(RESULTS / "comparison.json")

    if cmp_ is None:
        missing("results/comparison.json")

    else:
        mock_banner(cmp_, "comparison.json")

        try:
            # Overall summary
            summary = cmp_.get("summary", {})

            st.subheader("Overall Model Comparison")

            if summary:
                c1, c2, c3 = st.columns(3)

                c1.metric(
                    "Best Method",
                    summary.get("best_method", "Not available")
                )

                best_macro_f1 = summary.get("best_macro_f1")
                c2.metric(
                    "Best Macro F1",
                    f"{best_macro_f1:.4f}" if isinstance(best_macro_f1, (int, float)) else "Not available"
                )

                max_improvement = summary.get("max_improvement")
                c3.metric(
                    "Improvement Over Baseline",
                    f"{max_improvement:.4f}" if isinstance(max_improvement, (int, float)) else "Not available"
                )
            else:
                st.info("Overall summary is unavailable.")

            # Model rankings
            st.divider()
            st.subheader("Model Rankings by Macro F1")

            rankings = cmp_.get("rankings_by_macro_f1", [])

            if rankings:
                ranking_rows = []

                for item in rankings:
                    ranking_rows.append({
                        "Rank": item.get("rank"),
                        "Model": item.get("name"),
                        "Accuracy": item.get("accuracy"),
                        "Macro F1": item.get("macro_f1"),
                        "Minority F1": item.get("minority_f1"),
                        "Improvement": item.get(
                            "improvement_over_baseline_macro_f1"
                        )
                    })

                ranking_df = pd.DataFrame(ranking_rows)

                st.dataframe(
                    ranking_df,
                    width="stretch",
                    hide_index=True
                )

                if "Model" in ranking_df.columns and "Macro F1" in ranking_df.columns:
                    st.bar_chart(
                        ranking_df.set_index("Model")[["Macro F1"]]
                    )
            else:
                st.warning("No model rankings found.")

            # Detailed model comparison
            st.divider()
            st.subheader("Detailed Model Performance")

            methods = cmp_.get("methods", {})

            if methods:
                method_rows = []

                for key, values in methods.items():
                    method_rows.append({
                        "Model": values.get("name", key),
                        "Type": values.get("type", "Not specified"),
                        "Accuracy": values.get("accuracy"),
                        "Macro F1": values.get("macro_f1"),
                        "Minority F1": values.get("minority_f1_love_surprise"),
                        "Sharpness": values.get("sharpness"),
                        "Test Samples": values.get("n_test")
                    })

                method_df = pd.DataFrame(method_rows)

                st.dataframe(
                    method_df,
                    width="stretch",
                    hide_index=True
                )

                st.subheader("Accuracy vs Macro F1")

                chart_df = method_df.set_index("Model")[
                    ["Accuracy", "Macro F1"]
                ]

                st.bar_chart(chart_df)

                st.subheader("Per-Class F1 Scores")

                for key, values in methods.items():
                    with st.expander(values.get("name", key)):
                        per_class = values.get("per_class_f1", {})

                        if per_class:
                            class_df = pd.DataFrame.from_dict(
                                per_class,
                                orient="index",
                                columns=["F1 Score"]
                            )

                            st.dataframe(
                                class_df,
                                width="stretch"
                            )

                            st.bar_chart(class_df)
                        else:
                            st.info("Per-class F1 scores unavailable.")

            else:
                st.warning("No method comparison data found.")

            # Prompt template selection
            st.divider()
            st.subheader("Prompt Template Selection")

            selection = cmp_.get("prompt_template_selection", {})

            if selection:
                selected = selection.get(
                    "selected_template",
                    "Not available"
                )

                c1, c2 = st.columns(2)

                c1.metric("Selected Template", selected)

                c2.metric(
                    "Lambda",
                    selection.get("lambda", "Not available")
                )

                st.caption(selection.get("selection_formula", ""))

                scored = selection.get("scored_templates", {})

                if scored:
                    template_rows = []

                    for template_name, values in scored.items():
                        template_rows.append({
                            "Template": template_name,
                            "Validation Macro F1": values.get("val_macro_f1"),
                            "Validation Accuracy": values.get("val_accuracy"),
                            "Sharpness": values.get("sharpness"),
                            "Selection Score": values.get("selection_score")
                        })

                    template_df = pd.DataFrame(template_rows)

                    st.dataframe(
                        template_df,
                        width="stretch",
                        hide_index=True
                    )

                    st.bar_chart(
                        template_df.set_index("Template")[["Selection Score"]]
                    )
            else:
                st.warning("Prompt template selection data unavailable.")

        except (ValueError, TypeError, KeyError, AttributeError) as e:
            st.error(f"Invalid comparison.json structure: {e}")

